#!/usr/bin/env python3
"""
Generates STATUS.md: the board of what is already written and what is
missing, in both languages.

    python tools/status.py            # write STATUS.md
    python tools/status.py --check    # only report whether STATUS.md is out of date

A page counts as "to complete" while it still has a "## Still missing" (en)
or "## Ainda falta" (pt-BR) section. Once someone finishes the page and
deletes that section, it counts as done.

The board shows the base build (docs/). Pages written only for a newer game
build (builds/<N>/docs/) are listed at the end.

GitHub runs this script by itself on every change to main
(.github/workflows/status.yml), so nobody needs to edit STATUS.md.
"""
import argparse
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import build_manual as bm  # noqa: E402

OUT = bm.ROOT / "STATUS.md"
STUB = re.compile(r"^##\s+(Ainda falta|Still missing)\s*$", re.M)
DONE, TODO, MISSING = "✅", "📝", "❌"


def tip_count(folder_name, node_id):
    f = bm.TIPS / folder_name / f"{node_id}.md"
    if not f.exists():
        return 0
    text = re.sub(r"<!--.*?-->", "", f.read_text(encoding="utf-8"), flags=re.S)
    return len(re.findall(r"^##\s+", text, re.M))


def collect():
    """{key: {language: info}} in tree order, plus the title of each section."""
    _, langs = bm.load_all(bm.Diagrams())
    rows, sections = {}, {}
    for folder_name, (_, tree, _) in langs.items():
        def walk(node, depth):
            key = node.get("key", "")
            if key:
                top = key.split("/")[0]
                if depth == 1:
                    sections.setdefault(top, {})[folder_name] = node["title"]
                text = (bm.ROOT / node["file"]).read_text(encoding="utf-8") if node["file"] else ""
                rows.setdefault(key, {})[folder_name] = {
                    "title": node["title"], "file": node["file"], "folder": node["kind"] == "folder",
                    "depth": depth, "stub": bool(STUB.search(text)), "tips": tip_count(folder_name, node["id"]),
                }
            for c in node.get("children", []):
                walk(c, depth + 1)
        walk(tree, 0)
    return list(langs), rows, sections


def sort_key(key):
    return [(0, int(p)) if p.isdigit() else (1, p) for p in key.split("/")]


def cell(info):
    if not info:
        return MISSING
    mark = TODO if info["stub"] else DONE
    tips = f" · 💬 {info['tips']}" if info["tips"] else ""
    return f"{mark} [{info['file'].split('/')[-1]}]({info['file']}){tips}"


def render():
    order, rows, sections = collect()
    pages = {L: [r[L] for r in rows.values() if L in r] for L in order}
    lines = [
        "# Manual status / Painel do manual",
        "",
        "<!-- Generated by tools/status.py. Do not edit: GitHub rebuilds this file by itself. -->",
        "<!-- Gerado por tools/status.py. Não edite: o GitHub refaz este arquivo sozinho. -->",
        "",
        "What is already written and what is missing, in both languages. **Want to help? Pick a row with 📝 or ❌.**",
        "O que já está escrito e o que falta, nos dois idiomas. **Quer ajudar? Escolha uma linha com 📝 ou ❌.**",
        "",
        f"{DONE} done / pronta · {TODO} to complete (has \"Still missing\" / \"Ainda falta\") / para completar · "
        f"{MISSING} missing in this language / não existe neste idioma · 💬 tips / dicas",
        "",
        "| Language / Idioma | Pages / Páginas | " + DONE + " | " + TODO + " | " + MISSING + " | 💬 |",
        "|---|---|---|---|---|---|",
    ]
    for L in order:
        ps = pages[L]
        other = sum(1 for r in rows.values() if L not in r)
        lines.append(f"| {L} | {len(ps)} | {sum(not p['stub'] for p in ps)} | {sum(p['stub'] for p in ps)} | "
                     f"{other} | {sum(p['tips'] for p in ps)} |")
    lines += ["", "How to complete a page: [CONTRIBUTING.md](CONTRIBUTING.md#english). / Como completar uma página: "
              "[CONTRIBUTING.md](CONTRIBUTING.md#português).", ""]

    by_top = {}
    for key in sorted(rows, key=sort_key):
        by_top.setdefault(key.split("/")[0], []).append(key)
    for top, keys in by_top.items():
        names = sections.get(top, {})
        title = " / ".join(dict.fromkeys(names[L] for L in order if L in names)) or top
        todo = sum(1 for k in keys for L in order if not rows[k].get(L) or rows[k][L]["stub"])
        lines += ["", f"## {title}", "", f"To do / Para fazer: **{todo}**" if todo else "All done! / Tudo pronto!", ""]
        lines.append("| Page / Página | " + " | ".join(order) + " |")
        lines.append("|---|" + "---|" * len(order))
        for k in keys:
            any_info = next(rows[k][L] for L in order if L in rows[k])
            names = " / ".join(dict.fromkeys(rows[k][L]["title"] for L in order if L in rows[k]))
            indent = "&nbsp;&nbsp;&nbsp;" * max(0, any_info["depth"] - 1)
            label = f"{indent}**{names}**" if any_info["folder"] else f"{indent}{names}"
            lines.append(f"| {label} | " + " | ".join(cell(rows[k].get(L)) for L in order) + " |")
    lines += builds_section()
    return "\n".join(lines) + "\n"


def builds_section():
    """Pages that a newer game build changes, adds or removes (builds/<N>/docs/)."""
    base, extra = bm.builds_of(bm.read_config())
    if not extra:
        return []
    lines = ["", "## Newer game builds / Builds novas do jogo", "",
             f"Build {base} is the base (docs/). Each newer build only has what it changes. / "
             f"A build {base} é a base (docs/). Cada build nova só tem o que muda.", ""]
    for b in extra:
        docs = bm.layer_dir("docs", b, base)
        files = sorted(f for f in docs.rglob("*.md")
                       if not any(x.startswith(("_", ".")) for x in f.relative_to(docs).parts)) if docs.is_dir() else []
        lines += [f"### Build {b}", ""]
        for f in files:
            rel = f.relative_to(bm.ROOT).as_posix()
            text = f.read_text(encoding="utf-8")
            mark = "🗑️ removed / removida" if bm.REMOVED_RE.match(text) else (TODO if STUB.search(text) else DONE)
            lines.append(f"- {mark} [{rel}]({rel})")
        if not files:
            lines.append("- (tips only / só dicas)")
        lines.append("")
    return lines


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only check whether STATUS.md is up to date")
    args = ap.parse_args()
    try:
        text = render()
    except bm.ManualError as e:
        print("ERROR:", e)
        return 1
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if args.check:
        print("STATUS.md is up to date" if current == text else "STATUS.md is out of date: run python tools/status.py")
        return 0 if current == text else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("STATUS.md", "unchanged" if current == text else "updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
